import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

import {
  assertClean,
  commitReleasePlan,
  createReleasePlan,
  expandSelection,
  LEDGER_FILE,
  PLUGINS,
  PLAN_FILE,
  pnpmVersionSelection,
  readManifest,
  readSelectedVersions,
  RELEASE_BRANCH_PREFIX,
  resolveChangedSelection,
  runGit,
  tryGit,
  workingTreeChanges,
} from './lib.mjs'

const args = process.argv.slice(2)

const option = (name, fallback = undefined) => {
  const index = args.indexOf(name)
  return index >= 0 ? args[index + 1] : fallback
}
const hasFlag = (name) => args.includes(name)

const repo = path.resolve(option('--repo', process.cwd()))
const selection = option('--selection')
const baseBranch = option('--base-branch', 'master')
const allowAnyBranch = hasFlag('--allow-any-branch')
const noPush = hasFlag('--no-push')

const fail = (message) => {
  console.error(`prepare-release: ${message}`)
  process.exit(1)
}

try {
  if (!selection) fail('--selection ship-info|navy-staff|both is required')
  if (!fs.existsSync(path.join(repo, 'pnpm-workspace.yaml'))) {
    fail(`${repo} is not the plugin workspace root`)
  }

  const ids = expandSelection(selection)

  if (!allowAnyBranch) {
    const branch = tryGit(repo, ['symbolic-ref', '--short', 'HEAD'])
    if (branch !== baseBranch) {
      fail(`release preparation must run on ${baseBranch}, not ${branch}`)
    }
    const remote = tryGit(repo, [
      'rev-parse',
      `refs/remotes/origin/${baseBranch}`,
    ])
    const head = runGit(repo, ['rev-parse', 'HEAD'])
    if (remote && remote !== head) {
      fail(
        `${baseBranch} is not up to date with origin/${baseBranch}; ` +
          'update the base branch and run Prepare release again',
      )
    }
  }

  assertClean(repo)

  const baseCommit = runGit(repo, ['rev-parse', 'HEAD'])
  const baseVersions = readSelectedVersions(repo, ids)
  for (const id of ids) {
    if (readManifest(repo, PLUGINS[id].dir).private === true) {
      fail(`${PLUGINS[id].name} is private and cannot be released`)
    }
  }

  console.log(
    `Preparing ${ids.map((id) => `${PLUGINS[id].name}@${baseVersions[PLUGINS[id].name]}`).join(', ')}`,
  )
  const output = pnpmVersionSelection(repo, ids)
  if (output) console.log(output)

  const changes = workingTreeChanges(repo)
  if (changes.length === 0) {
    fail('no pending change intents applied for this selection')
  }

  const changedIds = resolveChangedSelection(repo, ids, baseVersions)
  const skippedIds = ids.filter((id) => !changedIds.includes(id))
  if (changedIds.length === 0) {
    fail(
      'no selected package has a pending change intent; nothing to release. ' +
        'Record an intent or choose a different selection.',
    )
  }
  if (skippedIds.length > 0) {
    console.log(
      `Skipping ${skippedIds
        .map((id) => PLUGINS[id].name)
        .join(', ')}: no pending change intents`,
    )
  }

  const allowed = new Set()
  for (const id of changedIds) {
    const dir = PLUGINS[id].dir
    allowed.add(`${dir}/package.json`)
    allowed.add(`${dir}/CHANGELOG.md`)
  }
  for (const change of changes) {
    const isIntentDelete =
      change.status === 'D' &&
      change.path.startsWith('.changeset/') &&
      change.path.endsWith('.md')
    const isLedger =
      change.path === LEDGER_FILE &&
      (change.status === 'A' || change.status === 'M')
    if (
      !isIntentDelete &&
      !isLedger &&
      !allowed.has(change.path)
    ) {
      fail(
        `unexpected file generated by pnpm version: ${change.status} ${change.path}`,
      )
    }
  }

  const plan = createReleasePlan({
    baseCommit,
    baseVersions,
    changes,
    repo,
    selection: changedIds,
  })

  const branch = `${RELEASE_BRANCH_PREFIX}${changedIds.join(
    '-',
  )}-${baseCommit.slice(0, 12)}-${process.env.GITHUB_RUN_ID ?? Date.now()}-${
    process.env.GITHUB_RUN_ATTEMPT ?? '1'
  }`

  if (!tryGit(repo, ['config', 'user.name'])) {
    runGit(repo, ['config', 'user.name', 'github-actions[bot]'])
  }
  if (!tryGit(repo, ['config', 'user.email'])) {
    runGit(repo, [
      'config',
      'user.email',
      '41898282+github-actions[bot]@users.noreply.github.com',
    ])
  }

  const title = `chore(release): prepare ${plan.releases
    .map((release) => `${release.name}@${release.to}`)
    .join(', ')}`
  const commit = commitReleasePlan({
    branch,
    message: title,
    plan,
    repo,
  })
  console.log(`Created ${branch} at ${commit}`)

  if (noPush) {
    console.log('--no-push: release branch was not pushed')
    process.exit(0)
  }

  if (!process.env.GH_TOKEN) {
    fail('GH_TOKEN is required to push and open the release pull request')
  }

  runGit(repo, ['push', 'origin', `HEAD:refs/heads/${branch}`])

  const body = [
    'This Release PR was generated by the Prepare release workflow.',
    '',
    `Base commit: \`${baseCommit}\``,
    'Selected packages:',
    ...plan.releases.map(
      (release) =>
        `- \`${release.name}\` ${release.from} -> ${release.to} (\`${release.tag}\`)`,
    ),
    '',
    `Generated files are recorded in \`${PLAN_FILE}\`. Do not edit this PR by`,
    'hand. If the base branch has advanced, close this PR and run Prepare',
    'release again from the updated base; stale Release PRs are rejected.',
    '',
    'Merging this PR publishes only the selected, validated tarballs through',
    'npm trusted publishing after the release validation passes.',
  ].join('\n')
  const bodyFile = path.join(
    fs.mkdtempSync(path.join(os.tmpdir(), 'release-body-')),
    'body.md',
  )

  try {
    fs.writeFileSync(bodyFile, body)
    const gh = spawnSync(
      'gh',
      [
        'pr',
        'create',
        '--base',
        baseBranch,
        '--head',
        branch,
        '--title',
        title,
        '--body-file',
        bodyFile,
      ],
      {
        cwd: repo,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      },
    )
    if (gh.status !== 0) {
      throw new Error(
        `gh pr create failed\n${gh.stdout ?? ''}${gh.stderr ?? ''}`,
      )
    }
    console.log(gh.stdout.trim())
  } finally {
    fs.rmSync(path.dirname(bodyFile), { recursive: true, force: true })
  }
} catch (error) {
  fail(error instanceof Error ? error.message : String(error))
}
