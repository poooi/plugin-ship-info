import path from 'node:path'

import {
  CHANGESET_DIR,
  classifyPath,
  diffFiles,
  evaluateIntentCoverage,
  gitFile,
  intentPathInHistory,
  LEDGER_FILE,
  parseIntent,
  parseReleasePlan,
  PLAN_FILE,
  RELEASE_BRANCH_PREFIX,
  runGit,
  tryGit,
} from './lib.mjs'

const args = process.argv.slice(2)
const option = (name, fallback = undefined) => {
  const index = args.indexOf(name)
  return index >= 0 ? args[index + 1] : fallback
}

const repo = option('--repo', process.cwd())
const base = option('--base')
const head = option('--head')
const branch = option('--branch', '')
const fail = (message) => {
  console.error(`changelog-check: ${message}`)
  process.exit(1)
}

const manifestAt = (rev, file) => {
  const raw = gitFile(repo, rev, file)
  if (raw === null) return null
  try {
    return JSON.parse(raw.toString('utf8'))
  } catch {
    return null
  }
}

try {
  if (!base || !head) fail('--base and --head are required')

  const changes = diffFiles(repo, base, head, { threeDot: true })
  const comparisonBase = runGit(repo, ['merge-base', base, head])
  const planChange = changes.find((change) => change.path === PLAN_FILE)
  const planAtHead = gitFile(repo, head, PLAN_FILE)
  const isReleaseBranch = branch.startsWith(RELEASE_BRANCH_PREFIX)

  // Only a changed release-plan.json marks a Release PR. A plan already merged
  // to the base is historical and must not make every later pull request look
  // like a release.
  if (planChange) {
    if (!isReleaseBranch) {
      fail(
        `${PLAN_FILE} may only be changed by Prepare release; ordinary pull ` +
          'requests must use .changeset intents',
      )
    }
    if (planAtHead === null) {
      fail(`${PLAN_FILE} was deleted by the Release PR`)
    }
    let plan
    try {
      plan = parseReleasePlan(planAtHead.toString('utf8'))
    } catch (error) {
      fail(error instanceof Error ? error.message : String(error))
    }
    if (plan.base.commit !== base) {
      fail(
        `Release PR base ${base} does not match plan base ${plan.base.commit}; ` +
          'the base advanced. Close this PR and rerun Prepare release.',
      )
    }
    console.log(
      'Release PR detected; Release PR validation checks the generated files.',
    )
    process.exit(0)
  }

  if (isReleaseBranch) {
    fail(`release branch ${branch} must change ${PLAN_FILE}`)
  }

  const ledgerChange = changes.find(
    (change) => change.path === LEDGER_FILE,
  )
  if (ledgerChange) {
    fail(
      `${LEDGER_FILE} is generated by pnpm version -r and may not be edited ` +
        'on an ordinary pull request',
    )
  }

  const renamedIntent = changes.find(
    (change) =>
      change.from &&
      change.from.startsWith(`${CHANGESET_DIR}/`) &&
      change.from.endsWith('.md') &&
      change.from !== `${CHANGESET_DIR}/README.md`,
  )
  if (renamedIntent) {
    fail(
      `change intent ${renamedIntent.from} was renamed; intents may not be ` +
        'renamed or reused. Add a new intent file instead.',
    )
  }

  const changelogEdit = changes.find(
    (change) =>
      /^packages\/(ship-info|navy-staff)\/CHANGELOG\.md$/.test(change.path) &&
      change.status !== 'A',
  )
  if (changelogEdit) {
    fail(
      `${changelogEdit.path} holds generated release notes; do not edit ` +
        'released sections. Record the change with a new .changeset intent.',
    )
  }

  for (const change of changes.filter((item) =>
    /^packages\/(ship-info|navy-staff)\/package\.json$/.test(item.path),
  )) {
    const from = manifestAt(comparisonBase, change.path)?.version ?? null
    const to =
      change.status === 'D'
        ? null
        : (manifestAt(head, change.path)?.version ?? null)
    if (from === to) continue
    // Narrow bootstrap: the initial setup normalizes the unpublished Navy
    // provisional version to the published npm placeholder before release
    // tooling exists on the base branch.
    const bootstrap =
      change.path === 'packages/navy-staff/package.json' &&
      from === '0.1.0' &&
      to === '1.2.0' &&
      tryGit(repo, [
        'cat-file',
        '-e',
        `${base}:scripts/release/validate-changelog.mjs`,
      ]) === null
    if (bootstrap) {
      console.log(
        `Allowing documented Navy baseline bootstrap ${from} -> ${to}.`,
      )
      continue
    }
    fail(
      `${change.path} changes the plugin version ${from} -> ${to}. Do not ` +
        'edit plugin versions by hand; use Prepare release.',
    )
  }

  const intentChanges = changes.filter(
    (change) =>
      change.path.startsWith(`${CHANGESET_DIR}/`) &&
      change.path.endsWith('.md') &&
      change.path !== `${CHANGESET_DIR}/README.md`,
  )
  const addedIntents = []
  for (const change of intentChanges) {
    if (change.status !== 'A') {
      fail(
        `existing change intent ${change.path} was ${change.status}; do not ` +
          'edit or delete old intents. Add a new intent file instead.',
      )
    }
    const id = path.basename(change.path, '.md')
    if (intentPathInHistory(repo, base, change.path)) {
      fail(
        `intent filename "${id}" already exists in the repository history ` +
          'reachable from the base. Intent filenames are never reused because ' +
          'pnpm ignores an id it has already consumed; choose a new filename.',
      )
    }
    const content = gitFile(repo, head, change.path)
    if (content === null) fail(`cannot read ${change.path} at ${head}`)
    try {
      addedIntents.push({
        ...parseIntent(content.toString('utf8'), change.path),
        path: change.path,
      })
    } catch (error) {
      fail(error instanceof Error ? error.message : String(error))
    }
  }

  const coverageFiles = changes.filter(
    (change) =>
      !(
        change.path.startsWith(`${CHANGESET_DIR}/`) ||
        classifyPath(change.path).kind === 'release-plan'
      ),
  )
  const coverage = evaluateIntentCoverage({
    changedFiles: coverageFiles,
    intents: addedIntents,
  })

  if (coverage.affected.length === 0) {
    console.log('No plugin runtime, package, shared, or build paths changed.')
  } else {
    console.log(
      `Affected plugins: ${coverage.affected.join(', ')}`,
    )
    for (const item of coverage.accepted) {
      console.log(
        `  ${item.name}: ${item.bump === 'none' ? 'none (explicit)' : item.bump} ` +
          `via ${item.intent}`,
      )
    }
  }

  if (coverage.errors.length > 0) {
    for (const error of coverage.errors) console.error(` - ${error}`)
    fail('change intent coverage is incomplete')
  }
  console.log('Changelog intent coverage is complete.')
} catch (error) {
  fail(error instanceof Error ? error.message : String(error))
}
